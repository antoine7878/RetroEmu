use std::error::Error;
use std::time::{SystemTime, UNIX_EPOCH};

use super::constants::CGB_FLAG;

pub const FRAME_RATE: u32 = 60;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GCMode {
    Dmg,
    Enhanced,
    Gbc,
}

impl GCMode {
    fn to_int(&self) -> usize {
        match self {
            Self::Dmg => 0,
            Self::Enhanced => 1,
            Self::Gbc => 1,
        }
    }

    pub fn initial_value(&self, addr: u16) -> u8 {
        let i = self.to_int();
        let vals = match addr {
            0xFF00 => [0xCF, 0xC7],
            0xFF01 => [0x00, 0x00],
            0xFF02 => [0x7E, 0x7F],
            0xFF04 => [0x18, 0xFF],
            0xFF05 => [0x00, 0x00],
            0xFF06 => [0x00, 0x00],
            0xFF07 => [0xF8, 0xF8],
            0xFF0F => [0xE1, 0xE1],
            0xFF10 => [0x80, 0x80],
            0xFF11 => [0xBF, 0xBF],
            0xFF12 => [0xF3, 0xF3],
            0xFF13 => [0xFF, 0xFF],
            0xFF14 => [0xBF, 0xBF],
            0xFF16 => [0x3F, 0x3F],
            0xFF17 => [0x00, 0x00],
            0xFF18 => [0xFF, 0xFF],
            0xFF19 => [0xBF, 0xBF],
            0xFF1A => [0x7F, 0x7F],
            0xFF1B => [0xFF, 0xFF],
            0xFF1C => [0x9F, 0x9F],
            0xFF1D => [0xFF, 0xFF],
            0xFF1E => [0xBF, 0xBF],
            0xFF20 => [0xFF, 0xFF],
            0xFF21 => [0x00, 0x00],
            0xFF22 => [0x00, 0x00],
            0xFF23 => [0xBF, 0xBF],
            0xFF24 => [0x77, 0x77],
            0xFF25 => [0xF3, 0xF3],
            0xFF26 => [0xF1, 0xF1],
            0xFF40 => [0x91, 0x91],
            0xFF41 => [0x81, 0xFF],
            0xFF42 => [0x00, 0x00],
            0xFF43 => [0x00, 0x00],
            0xFF44 => [0x91, 0xFF],
            0xFF45 => [0x00, 0x00],
            0xFF46 => [0xFF, 0x00],
            0xFF47 => [0xFC, 0xFC],
            0xFF48 => [0xFF, 0xFF],
            0xFF49 => [0xFF, 0xFF],
            0xFF4A => [0x00, 0x00],
            0xFF4B => [0x00, 0x00],
            0xFF4C => [0xFF, 0xFF],
            0xFF4D => [0xFF, 0x7E],
            0xFF4F => [0xFF, 0xFE],
            0xFF50 => [0xFF, 0xFF],
            0xFF51 => [0xFF, 0xFF],
            0xFF52 => [0xFF, 0xFF],
            0xFF53 => [0xFF, 0xFF],
            0xFF54 => [0xFF, 0xFF],
            0xFF55 => [0xFF, 0xFF],
            0xFF56 => [0xFF, 0x3E],
            0xFF68 => [0xFF, 0xFF],
            0xFF69 => [0xFF, 0xFF],
            0xFF6A => [0xFF, 0xFF],
            0xFF6B => [0xFF, 0xFF],
            0xFF70 => [0xFF, 0xF8],
            0xFFFF => [0x00, 0x00],
            _ => return 0xFF,
        };
        vals[i]
    }
}

#[derive(Debug, Clone)]
pub struct Config {
    pub instructions_per_frame: u64,
    pub rng_seed: u32,
    pub mode: GCMode,
}

impl Config {
    pub fn new(rom: &[u8]) -> Result<Self, Box<dyn Error>> {
        let rng_seed = SystemTime::now().duration_since(UNIX_EPOCH)?.subsec_nanos();
        let mode = Self::mode(rom);
        Ok(Self { rng_seed, mode, instructions_per_frame: 69905 })
    }

    fn mode(rom: &[u8]) -> GCMode {
        match rom[CGB_FLAG as usize] {
            0x80 => GCMode::Gbc,
            0xC0 => GCMode::Enhanced,
            _ => GCMode::Dmg,
        }
    }
}
